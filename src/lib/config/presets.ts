export function applyPreset(
  appearance: AppearanceConfig,
  layout: LayoutConfig,
  presetId: string,
): { appearance: AppearanceConfig; layout: LayoutConfig } {
  const p = DESIGN_PRESETS.find((x) => x.id === presetId);
  if (!p) return { appearance, layout };
  return {
    appearance: {
      ...appearance,
      ...p.appearance,
      background: { ...appearance.background, ...(p.appearance.background ?? {}) },
      preset: p.id,
    },
    // Presets that don't define spacing fall back to the regular defaults.
    layout: { ...layout, fullWidth: false, padding: 24, gap: 16, ...(p.layout ?? {}) },
  };
}
